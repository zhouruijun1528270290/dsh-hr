import { readFile, writeFile } from 'node:fs/promises'
import { Script } from 'node:vm'

// 顺序固定：contract（共享常量）→ live2d 渲染器（HRMark 依赖它）→ 候选人摄像头（InterviewView 右屏依赖它）
// → client（面板本体）。四段都是「无模块语法」的文本，拼进同一个工厂函数作用域里，由最后的 module.exports 收口。
const BUNDLE_PARTS = [
  { name: 'src/live2d-avatar.js', label: 'live2d renderer' },
  { name: 'src/candidate-camera.js', label: 'candidate camera' },
  { name: 'src/client.js', label: 'client' },
]

// 测试用「这一段当作不存在」的哨兵：缺件必须让构建失败，而不是内联一个静默占位。
// 静默占位会让「忘了拿候选人组件」变成线上一个空白右屏，构建期却一路绿灯。
export const MISSING_PART = Symbol.for('dsh-hr-interview.build.missing-part')

const hasOwn = (value, key) => Object.prototype.hasOwnProperty.call(value, key)

const missingPartError = (name) => {
  const error = new Error(`构建缺少必需段落 ${name}：双屏依赖它，缺件不能静默跳过（先补齐该文件再构建）`)
  error.code = 'ENOENT'
  error.part = name
  return error
}

export async function buildClient({ root, outputFile, write = true, overrides = {} } = {}) {
  const patched = overrides && typeof overrides === 'object' ? overrides : {}
  // overrides 只服务于测试：把某一段换成探针源码，用来断言「props 真的传给了候选人组件」，
  // 而不必知道真组件内部长什么样。生产构建永远读磁盘上的真文件。
  const readPart = async (name) => {
    if (hasOwn(patched, name)) {
      if (patched[name] === MISSING_PART) throw missingPartError(name)
      return String(patched[name])
    }
    try {
      return await readFile(`${root}${name}`, 'utf8')
    } catch (error) {
      // 只有「文件不存在」翻译成缺件；语法/权限等真实故障原样抛出，别伪装成缺文件。
      if (error && error.code === 'ENOENT') throw missingPartError(name)
      throw error
    }
  }
  const [source, renderer, candidate, contractSource, manifest] = await Promise.all([
    readPart('src/client.js'),
    readPart('src/live2d-avatar.js'),
    readPart('src/candidate-camera.js'),
    readPart('lib/contract.js'),
    readPart('package.json'),
  ])
  const pkg = JSON.parse(manifest)
  const contract = contractSource.replace(/^import .*$/gm, '').replace(/^export /gm, '').trim()
  const texts = { 'src/live2d-avatar.js': renderer, 'src/candidate-camera.js': candidate, 'src/client.js': source }
  for (const name of Object.keys(texts)) {
    // 内联文本一旦出现模块语法，node --check / vm Script 会直接炸；这里提前给出可读的报错。
    if (/^import .*$/m.test(texts[name]) || /^export /m.test(texts[name])) throw new Error(`${name} must stay a plain browser script (no import/export)`)
    if (texts[name].includes('__ModuleLoader__')) throw new Error(`${name} must not contain the loader wrapper`)
  }
  if (!source.includes('HR_CLIENT_REMOTE') || !contract.includes('HR_DESCRIPTORS')) throw new Error('Remote contract is missing')
  if (!renderer.includes('hrLive2dComponent')) throw new Error('Live2D renderer entry hrLive2dComponent is missing')
  if (!candidate.includes('hrCandidateCameraComponent')) throw new Error('Candidate camera entry hrCandidateCameraComponent is missing')
  // client 必须通过工厂取组件：直接写组件名会让「换实现」变成改两处。
  if (!source.includes('const CandidateCamera = hrCandidateCameraComponent(React)')) throw new Error('client must resolve CandidateCamera through hrCandidateCameraComponent(React)')
  const output = `// Generated by scripts/build.mjs; do not edit directly.\nwindow.__ModuleLoader__.load({ id: ${JSON.stringify(pkg.name)}, factory: (require) => {\nvar module = { exports: {} };\nvar exports = module.exports;\n${contract}\n${renderer}\n${candidate}\n${source}\nreturn module.exports;\n} });\n`
  new Script(output, { filename: 'dsh-hr-interview/client.js' })
  if (write) await writeFile(outputFile || `${root}client.js`, output, 'utf8')
  return { output, packageName: pkg.name, parts: [...BUNDLE_PARTS.map((part) => part.name), 'lib/contract.js'] }
}
